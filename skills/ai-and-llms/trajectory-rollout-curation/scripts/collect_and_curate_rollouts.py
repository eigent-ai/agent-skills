#!/usr/bin/env python3
"""Collect, score, and curate multi-turn agent trajectories using scripted, rule-based, and random policies.

Implements `trajectory-rollout-curation`:
- Loads the `tasks_dataset.jsonl` and `env_core.py` generated by `multi-turn-env-scaffold`.
- Executes 4 policies per task row (group_size = 4):
  1. `scripted_optimal`: BFS shortest-path solver that navigates around hazards, runs INSPECT, then PATCH.
  2. `rule_based_greedy`: Manhattan greedy mover that navigates toward target, runs INSPECT, then PATCH.
  3. `noisy_Exploratory`: Rule-based policy that occasionally emits an untagged thought or suboptimal step.
  4. `random_policy`: Uniform random action chooser across valid commands.
- Preserves dual message-and-token trace segments with explicit `loss_mask` (1 for assistant actions, 0 for env observations).
- Computes composite rewards, group-relative conciseness bonuses, and normalized GRPO group advantages.
- Filters clean winning trajectories into `sft_examples.jsonl` while keeping `tasks_dataset.jsonl`,
  `recorded_trajectories.jsonl`, `sft_examples.jsonl`, and RL policy optimization strictly distinct.
"""

from __future__ import annotations
import argparse
from collections import deque
import hashlib
import importlib.util
import json
import math
import random
from pathlib import Path
from typing import Any


def tokenize_whitespace_ids(text: str) -> list[int]:
    """Deterministic local token IDs for trace-graph alignment verification (no external API needed)."""
    tokens = text.split()
    return [int(hashlib.md5(tok.encode("utf-8")).hexdigest()[:6], 16) for tok in tokens]


def bfs_next_move(
    agent_pos: list[int],
    target_pos: list[int],
    hazards: list[list[int]],
    grid_size: int = 4,
) -> str:
    start = (agent_pos[0], agent_pos[1])
    goal = (target_pos[0], target_pos[1])
    if start == goal:
        return "INSPECT"
    blocked = {(h[0], h[1]) for h in hazards}
    queue: deque[tuple[tuple[int, int], list[str]]] = deque([(start, [])])
    visited = {start}
    dirs = [
        ("UP", -1, 0),
        ("DOWN", 1, 0),
        ("LEFT", 0, -1),
        ("RIGHT", 0, 1),
    ]
    while queue:
        (r, c), path = queue.popleft()
        for name, dr, dc in dirs:
            nr, nc = r + dr, c + dc
            if 0 <= nr < grid_size and 0 <= nc < grid_size and (nr, nc) not in visited:
                if (nr, nc) == goal:
                    return (path + [name])[0]
                if (nr, nc) not in blocked:
                    visited.add((nr, nc))
                    queue.append(((nr, nc), path + [name]))
    # Fallback if temporarily surrounded by hazards
    for name, dr, dc in dirs:
        nr, nc = start[0] + dr, start[1] + dc
        if 0 <= nr < grid_size and 0 <= nc < grid_size and (nr, nc) not in blocked:
            return name
    return "RIGHT"


def choose_policy_action(policy_name: str, state: dict[str, Any], rng: random.Random) -> str:
    pos = state["agent_pos"]
    target = state["target_pos"]
    hazards = state["hazards"]
    inspected = state["inspected"]

    if policy_name == "scripted_optimal":
        if pos == target and not inspected:
            act = "INSPECT"
            thought = "At target node; run diagnostic inspection."
        elif pos == target and inspected:
            act = "PATCH"
            thought = "Inspection complete; apply verified patch."
        else:
            act = bfs_next_move(pos, target, hazards, state["grid_size"])
            thought = f"Shortest hazard-free BFS step toward {tuple(target)} is {act}."
        return f"<think>{thought}</think><action>{act}</action>"

    if policy_name == "rule_based_greedy":
        if pos == target and not inspected:
            return "<think>Reached target. Inspecting bug.</think><action>INSPECT</action>"
        if pos == target and inspected:
            return "<think>Bug inspected. Applying patch now.</think><action>PATCH</action>"
        dr = target[0] - pos[0]
        dc = target[1] - pos[1]
        preferred = []
        if dr > 0:
            preferred.append(("DOWN", [pos[0] + 1, pos[1]]))
        elif dr < 0:
            preferred.append(("UP", [pos[0] - 1, pos[1]]))
        if dc > 0:
            preferred.append(("RIGHT", [pos[0], pos[1] + 1]))
        elif dc < 0:
            preferred.append(("LEFT", [pos[0], pos[1] - 1]))
        for move_name, next_cell in preferred:
            if next_cell not in hazards:
                return f"<think>Greedy step {move_name} toward target while avoiding visible hazards safely.</think><action>{move_name}</action>"
        fallback_move = preferred[0][0] if preferred else "RIGHT"
        return f"<think>Attempting greedy direction {fallback_move}.</think><action>{fallback_move}</action>"

    if policy_name == "noisy_exploratory":
        # On turn 1 with 50% probability, emit a malformed action to test soft-penalty recovery
        if state["turn"] == 0 and rng.random() < 0.5:
            return "I think I should move toward the target first without XML action tags."
        if pos == target and not inspected:
            return "<think>Now on target, inspecting.</think><action>INSPECT</action>"
        if pos == target and inspected:
            return "<think>Patching target node after inspection.</think><action>PATCH</action>"
        act = bfs_next_move(pos, target, hazards, state["grid_size"])
        return f"<think>Exploratory recovery step choosing {act} after checking board state.</think><action>{act}</action>"

    # random_policy
    valid = ["UP", "DOWN", "LEFT", "RIGHT", "INSPECT", "PATCH"]
    chosen = rng.choice(valid)
    return f"<think>Randomly sampling action {chosen}.</think><action>{chosen}</action>"


def run_single_rollout(
    env_cls: Any,
    task_row: dict[str, Any],
    policy_name: str,
    rollout_idx: int,
) -> dict[str, Any]:
    env = env_cls(max_turns=8, invalid_penalty=-0.10)
    obs = env.reset(task_row)
    rng = random.Random(int(task_row["example_seed"]) + rollout_idx * 101)

    messages: list[dict[str, str]] = [
        {
            "role": "system",
            "content": "You are a diagnostic repair agent. Always output <think>...</think><action>...</action>.",
        },
        {"role": "user", "content": task_row["initial_prompt"] + "\n" + obs["observation_text"]},
    ]
    token_segments: list[dict[str, Any]] = []
    for idx, m in enumerate(messages):
        t_ids = tokenize_whitespace_ids(m["content"])
        token_segments.append(
            {
                "turn": 0,
                "role": m["role"],
                "token_count": len(t_ids),
                "loss_mask": 0,
                "token_ids_sha256": hashlib.sha256(json.dumps(t_ids).encode("utf-8")).hexdigest()[:16],
            }
        )

    step_rewards: list[float] = []
    while not obs["terminated"]:
        state = obs["state"]
        completion = choose_policy_action(policy_name, state, rng)
        messages.append({"role": "assistant", "content": completion})
        comp_ids = tokenize_whitespace_ids(completion)
        token_segments.append(
            {
                "turn": state["turn"] + 1,
                "role": "assistant",
                "token_count": len(comp_ids),
                "loss_mask": 1,  # Only assistant action tokens receive policy gradient loss
                "token_ids_sha256": hashlib.sha256(json.dumps(comp_ids).encode("utf-8")).hexdigest()[:16],
            }
        )

        obs = env.step(completion)
        step_rewards.append(float(obs["step_reward"]))
        messages.append({"role": "user", "content": obs["observation_text"]})
        obs_ids = tokenize_whitespace_ids(obs["observation_text"])
        token_segments.append(
            {
                "turn": obs["state"]["turn"],
                "role": "user",
                "token_count": len(obs_ids),
                "loss_mask": 0,  # Environment observations are masked out of policy loss
                "token_ids_sha256": hashlib.sha256(json.dumps(obs_ids).encode("utf-8")).hexdigest()[:16],
            }
        )

    final_state = obs["state"]
    s_out = 1 if final_state["patched"] else 0
    progress_score = (0.4 if final_state["agent_pos"] == final_state["target_pos"] else 0.0) + (
        0.3 if final_state["inspected"] else 0.0
    ) + (0.3 if final_state["patched"] else 0.0)
    format_ratio = final_state["format_hits"] / float(max(1, final_state["turn"]))
    s_proc = round(0.8 * progress_score + 0.2 * format_ratio, 4)

    action_token_count = sum(seg["token_count"] for seg in token_segments if seg["loss_mask"] == 1)
    total_step_r = round(sum(step_rewards), 4)
    base_composite = round(1.0 * s_out + 0.2 * format_ratio + final_state["step_Penalty_accum"], 4)

    return {
        "artifact_type": "recorded_trajectory",
        "trajectory_id": f"{task_row['task_id']}__r{rollout_idx}_{policy_name}",
        "task_id": task_row["task_id"],
        "group_id": f"grp_{task_row['task_id']}",
        "policy_name": policy_name,
        "example_seed": int(task_row["example_seed"]),
        "difficulty_bucket": task_row["difficulty_bucket"],
        "s_out": s_out,
        "s_proc": s_proc,
        "step_reward_sum": total_step_r,
        "base_composite_reward": base_composite,
        "composite_reward": base_composite,
        "conciseness_bonus": 0.0,
        "group_advantage": 0.0,
        "action_token_count": action_token_count,
        "turns_taken": int(final_state["turn"]),
        "invalid_moves": int(final_state["invalid_moves"]),
        "termination_reason": str(final_state["termination_reason"]),
        "messages": messages,
        "token_segments": token_segments,
    }


def score_group_advantages(group_rollouts: list[dict[str, Any]]) -> bool:
    """Apply group-relative conciseness bonus on passing rollouts and compute normalized GRPO advantages."""
    passing_tokens = [r["action_token_count"] for r in group_rollouts if r["s_out"] == 1]
    if passing_tokens:
        min_t, max_t = min(passing_tokens), max(passing_tokens)
        for r in group_rollouts:
            if r["s_out"] == 1:
                if max_t > min_t:
                    eff = (max_t - r["action_token_count"]) / float(max_t - min_t)
                    bonus = round(0.10 * eff, 4)
                else:
                    bonus = 0.10
                r["conciseness_bonus"] = bonus
                r["composite_reward"] = round(r["base_composite_reward"] + bonus, 4)

    rewards = [r["composite_reward"] for r in group_rollouts]
    mean_r = sum(rewards) / float(len(rewards))
    var_r = sum((x - mean_r) ** 2 for x in rewards) / float(len(rewards))
    std_r = math.sqrt(var_r)
    zero_var = std_r < 1e-8
    for r in group_rollouts:
        r["group_advantage"] = 0.0 if zero_var else round((r["composite_reward"] - mean_r) / std_r, 4)
    return zero_var


def main() -> None:
    parser = argparse.ArgumentParser(description="Collect and curate multi-turn agent trajectories.")
    parser.add_argument(
        "--env-dir",
        default="rl-env-skills/examples/grid-repair-env",
        help="Directory containing env_core.py and tasks_dataset.jsonl",
    )
    args = parser.parse_args()

    env_dir = Path(args.env_dir)
    spec = importlib.util.spec_from_file_location("env_core", env_dir / "env_core.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    tasks: list[dict[str, Any]] = []
    with (env_dir / "tasks_dataset.jsonl").open("r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                tasks.append(json.loads(line))

    policies = ["scripted_optimal", "rule_based_greedy", "noisy_exploratory", "random_policy"]
    all_trajectories: list[dict[str, Any]] = []
    zero_variance_groups = 0

    for task_row in tasks:
        grp = [
            run_single_rollout(mod.ReproducibleGridRepairEnv, task_row, pol, idx)
            for idx, pol in enumerate(policies)
        ]
        if score_group_advantages(grp):
            zero_variance_groups += 1
        all_trajectories.extend(grp)

    traj_path = env_dir / "recorded_trajectories.jsonl"
    with traj_path.open("w", encoding="utf-8") as f:
        for t in all_trajectories:
            f.write(json.dumps(t) + "\n")

    # Filter recorded trajectories into clean SFT examples (s_out == 1 and invalid_moves == 0)
    sft_examples: list[dict[str, Any]] = []
    for t in all_trajectories:
        if t["s_out"] == 1 and t["invalid_moves"] == 0:
            sft_examples.append(
                {
                    "artifact_type": "supervised_training_example",
                    "sft_example_id": f"sft__{t['trajectory_id']}",
                    "source_trajectory_id": t["trajectory_id"],
                    "task_id": t["task_id"],
                    "policy_origin": t["policy_name"],
                    "composite_reward": t["composite_reward"],
                    "messages": t["messages"],
                }
            )

    sft_path = env_dir / "sft_examples.jsonl"
    with sft_path.open("w", encoding="utf-8") as f:
        for ex in sft_examples:
            f.write(json.dumps(ex) + "\n")

    # Verify token-mask alignment invariant across all recorded trajectories
    mask_check_passed = all(
        all(
            (seg["loss_mask"] == 1 if seg["role"] == "assistant" else seg["loss_mask"] == 0)
            for seg in t["token_segments"]
        )
        for t in all_trajectories
    )

    policy_summary: dict[str, dict[str, Any]] = {}
    for pol in policies:
        sub = [t for t in all_trajectories if t["policy_name"] == pol]
        policy_summary[pol] = {
            "rollouts": len(sub),
            "win_rate": round(sum(t["s_out"] for t in sub) / float(len(sub)), 4),
            "mean_reward": round(sum(t["composite_reward"] for t in sub) / float(len(sub)), 4),
            "mean_invalid_moves": round(sum(t["invalid_moves"] for t in sub) / float(len(sub)), 4),
        }

    summary = {
        "env_name": env_dir.name,
        "artifact_distinction_audit": {
            "task_dataset_path": str(env_dir / "tasks_dataset.jsonl"),
            "task_dataset_count": len(tasks),
            "recorded_trajectories_path": str(traj_path),
            "recorded_trajectories_count": len(all_trajectories),
            "sft_examples_path": str(sft_path),
            "sft_examples_count": len(sft_examples),
            "rl_policy_optimisation_performed": False,
            "rl_policy_optimisation_note": (
                "Exporting recorded_trajectories.jsonl and sft_examples.jsonl is offline data collection "
                "and SFT curation, NOT RL policy optimisation (which requires live policy logprobs and "
                "gradient updates such as GRPO/CISPO/PPO)."
            ),
        },
        "group_count": len(tasks),
        "group_size": len(policies),
        "zero_variance_groups": zero_variance_groups,
        "token_mask_alignment_passed": mask_check_passed,
        "sft_purity_check_passed": all(
            ex["composite_reward"] >= 1.0 for ex in sft_examples
        ) and len(sft_examples) > 0,
        "policy_performance": policy_summary,
        "all_checks_passed": bool(
            mask_check_passed
            and len(all_trajectories) == len(tasks) * len(policies)
            and len(sft_examples) > 0
            and zero_variance_groups == 0
        ),
    }

    summary_path = env_dir / "curation_summary.json"
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
